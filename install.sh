def w(s, d=0.0):
    sys.stdout.write(s)
    sys.stdout.flush()
    if d:
        time.sleep(d)


def banner():
    w("\n")
    for line, c in zip(ART, COLORS):
        w(f"{E}[1;38;5;{c}m  {line}{RS}\n", 0.07)
    w(f"\n  {E}[38;5;213m✦ ━━━━━━━━━━━ {RS}{E}[1m")
